@pytest.fixture
async def production_seed(session):
    await seed_mock(session)
    await seed_catalog(session)
    await seed_full(session)
    return session


async def test_model_outputs_match_the_expected_ingredients(production_seed):
    wrong = []
    for query, expected in CASES:
        match = await match_ingredient(production_seed, query)
        got = match.ingredient.name if match else None
        if got != expected:
            wrong.append(f"{query!r}: expected {expected!r}, got {got!r}")
    assert not wrong, "\n".join(wrong)


def test_the_list_covers_hits_and_deliberate_misses():
    assert len(CASES) >= 200
    assert len({q for q, _ in CASES}) == len(CASES)
    assert sum(e is None for _, e in CASES) >= 10
